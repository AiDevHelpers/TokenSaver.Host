using AiDevTools.TokenSaver.ContextHelper.Models;

using Microsoft.Extensions.Logging;

using System.Collections.Concurrent;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Threading;

namespace AiDevTools.TokenSaver.MCP.Services;

/// <summary>
///     Maintains a per-workspace, hash-gated cache of the optimized instruction set at
///     <c>.tokensaver/context/instructions/</c>: the combined main doc (<c>main.md</c> — the
///     machine-global <c>CLAUDE.md</c> plus every project-level <c>CLAUDE.md</c> found by walking
///     from the workspace root up to the filesystem root, see <see cref="DiscoverClaudeMdChain" />),
///     each discovered sub-doc under <c>subdocs/&lt;slug&gt;.md</c>, and a <c>manifest.json</c>
///     recording the source hash and each sub-doc's frontmatter. <see cref="InstructionOptimizerService" />
///     reads this cache to sync per-client target files (preserving the main/sub-doc split so each
///     client's own lazy-loading still applies); <see cref="TryGetInjectableDoc" /> lets
///     <c>ContextInterceptMiddleware</c> inject a task-type-matched sub-doc directly into a
///     request instead of relying on that lazy loading, for requests that need it regardless of
///     which files they touch.
///     <para>
///     Regeneration only happens when the combined content hash of the whole chain + all
///     discovered sub-docs changes — see <see cref="ComputeSourceHash" />. A
///     <see cref="FileSystemWatcher" /> on the global instructions directory (lazily started on
///     first <see cref="EnsureFresh" /> call) re-checks every workspace that has called
///     <see cref="EnsureFresh" /> at least once whenever the global doc or any <c>.md</c> file
///     under it changes — project-level <c>CLAUDE.md</c> edits aren't separately watched, but get
///     picked up on the next <see cref="EnsureFresh" /> call (every session connect) regardless.
///     </para>
/// </summary>
internal sealed partial class InstructionCacheService : IDisposable
{
    [LoggerMessage(Level = LogLevel.Debug, Message = "Instruction cache regenerated for {WorkspaceRoot}: {Count} sub-doc(s)")]
    private static partial void LogRegenerated(ILogger logger, string workspaceRoot, int count);

    [LoggerMessage(Level = LogLevel.Warning, Message = "Instruction cache regeneration failed for {WorkspaceRoot}")]
    private static partial void LogRegenerationFailed(ILogger logger, string workspaceRoot, Exception ex);

    [LoggerMessage(Level = LogLevel.Debug, Message = "Instruction source change detected — re-checking {Count} known workspace(s)")]
    private static partial void LogSourceChanged(ILogger logger, int count);

    [LoggerMessage(Level = LogLevel.Information, Message = "No CLAUDE.md found anywhere for {WorkspaceRoot} — bootstrapped a starter one at {Path}")]
    private static partial void LogBootstrapped(ILogger logger, string workspaceRoot, string path);

    [LoggerMessage(Level = LogLevel.Warning, Message = "Failed to bootstrap a starter CLAUDE.md for {WorkspaceRoot}; continuing without one")]
    private static partial void LogBootstrapFailed(ILogger logger, string workspaceRoot, Exception ex);

    private const string StarterClaudeMdContent =
        "# CLAUDE.md\n\n" +
        "Project-specific instructions for Claude Code and other AI agents working in this " +
        "repository.\n\n" +
        "This file was auto-generated by TokenSaver because no CLAUDE.md existed yet for this " +
        "project (repoHelper.optimizeInstructions is on by default). Edit it freely — add build/" +
        "test commands, architecture notes, or conventions specific to this codebase; TokenSaver " +
        "only creates this file once and never overwrites it afterward.\n";

    private static readonly JsonSerializerOptions JsonOptions = new() { WriteIndented = true };

    private readonly ILogger<InstructionCacheService> _logger;
    private readonly ConcurrentDictionary<string, byte> _knownWorkspaceRoots = new(StringComparer.OrdinalIgnoreCase);
    private readonly ConcurrentDictionary<string, Lock> _workspaceLocks = new(StringComparer.OrdinalIgnoreCase);
    private readonly Lock _watcherSync = new();
    private FileSystemWatcher? _watcher;

    public InstructionCacheService(ILogger<InstructionCacheService> logger)
    {
        _logger = logger;
    }

    private static string CacheDir(string workspaceRoot) =>
        Path.Combine(workspaceRoot, ".tokensaver", "context", "instructions");

    private static string SubDocsDir(string workspaceRoot) => Path.Combine(CacheDir(workspaceRoot), "subdocs");

    /// <summary>
    ///     Path to the cached main doc for <paramref name="workspaceRoot" /> — the machine-global
    ///     <c>CLAUDE.md</c> verbatim when no project-level <c>CLAUDE.md</c> was found, otherwise
    ///     the whole discovered chain concatenated with source-path labels (see
    ///     <see cref="DiscoverClaudeMdChain" />). Missing when no doc in the chain exists at all.
    /// </summary>
    public static string MainDocCachePath(string workspaceRoot) => Path.Combine(CacheDir(workspaceRoot), "main.md");

    /// <summary>
    ///     Regenerates the on-disk cache for <paramref name="workspaceRoot" /> when the resolved
    ///     chain of <c>CLAUDE.md</c> docs (or any of their discovered sub-docs) has changed since
    ///     the last call, otherwise returns the existing manifest unchanged. Registers
    ///     <paramref name="workspaceRoot" /> with the file-system watcher so future out-of-band
    ///     source edits regenerate it too.
    /// </summary>
    /// <param name="autoSplitOversized">
    ///     When true (<c>repoHelper.autoSplitOversizedInstructions</c>, on by default), each doc
    ///     in the chain gets run through <see cref="InstructionAutoSplitter" /> before sub-doc
    ///     discovery — an oversized doc's large sections are extracted into synthetic sub-docs and
    ///     the doc's content shrunk to a pointer, purely in the in-memory/cached representation.
    ///     The source file on disk is never read back into or written from this step — only
    ///     <c>.tokensaver/context/instructions/</c> (already a derived cache) and per-client sync
    ///     targets ever reflect the split. Defaults to false here at the method level (this
    ///     parameter default is just this method's own conservative default); callers resolve the
    ///     real on-by-default value from config themselves — see
    ///     <c>InstructionOptimizerService.EnsureSynced</c>.
    /// </param>
    public InstructionManifest EnsureFresh(string workspaceRoot, bool autoSplitOversized = false)
    {
        _knownWorkspaceRoots[workspaceRoot] = 0;
        EnsureWatcherStarted();

        // Serialize per workspace root: EnsureFresh's read-manifest/compare-hash/regenerate
        // sequence isn't safe against concurrent execution for the same root, and it genuinely
        // does run concurrently in practice — the file-system watcher's OnSourceChanged handler
        // (see below) calls back into this same method on a thread-pool thread, which can race an
        // explicit caller-thread invocation triggered by the very same source-file write. Without
        // this lock, two overlapping calls can each read a manifest the other is mid-write on
        // (only survivable because ReadManifest now also tolerates IOException), or — worse —
        // interleave such that a caller observes a stale-looking hash match despite the source
        // having actually changed. Locking the whole method body (not just the write) is what
        // actually closes that: it makes the two racing calls fully sequential instead of merely
        // making each individual file op safe.
        lock (_workspaceLocks.GetOrAdd(workspaceRoot, static _ => new Lock()))
        {
            return EnsureFreshCore(workspaceRoot, autoSplitOversized);
        }
    }

    private InstructionManifest EnsureFreshCore(string workspaceRoot, bool autoSplitOversized)
    {
        IReadOnlyList<(string Path, string Content)> chain = DiscoverClaudeMdChain(workspaceRoot);
        if (chain.Count == 0)
        {
            chain = BootstrapWorkspaceClaudeMd(workspaceRoot);
            if (chain.Count == 0)
            {
                return new InstructionManifest();
            }
        }

        HashSet<string> seenSubDocPaths = new(StringComparer.OrdinalIgnoreCase);
        HashSet<string> seenSlugs = new(StringComparer.OrdinalIgnoreCase);
        List<DiscoveredSubDoc> subDocs = [];

        if (autoSplitOversized)
        {
            List<(string Path, string Content)> shrunkChain = new(chain.Count);
            foreach ((string path, string content) in chain)
            {
                (string shrunk, IReadOnlyList<DiscoveredSubDoc> extracted) =
                    InstructionAutoSplitter.Split(path, content, seenSlugs, _logger);
                shrunkChain.Add((path, shrunk));
                subDocs.AddRange(extracted);
            }

            chain = shrunkChain;
        }

        foreach ((string path, string content) in chain)
        {
            subDocs.AddRange(InstructionSubDocParser.DiscoverSubDocs(path, content, seenSubDocPaths, seenSlugs));
        }

        string mainContent = BuildCombinedMainContent(chain);
        string sourceHash = ComputeSourceHash(chain, subDocs);

        string cacheDir = CacheDir(workspaceRoot);
        string manifestPath = Path.Combine(cacheDir, "manifest.json");

        InstructionManifest? existing = ReadManifest(manifestPath);
        if (existing is not null && existing.SourceHash == sourceHash)
        {
            return existing;
        }

        try
        {
            return Regenerate(workspaceRoot, mainContent, subDocs, sourceHash);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            LogRegenerationFailed(_logger, workspaceRoot, ex);
            return existing ?? new InstructionManifest();
        }
    }

    /// <summary>
    ///     Resolves the full ordered chain of <c>CLAUDE.md</c> docs that apply to
    ///     <paramref name="workspaceRoot" />: the machine-global doc first (if present), then any
    ///     project-level <c>CLAUDE.md</c> found by walking from <paramref name="workspaceRoot" />
    ///     up through enclosing git repositories — outermost ancestor first,
    ///     <paramref name="workspaceRoot" />'s own <c>CLAUDE.md</c> last. Mirrors Claude Code's own
    ///     project-instructions discovery (this is the same order it presents multiple CLAUDE.md
    ///     files in: global, then broadest project, down to the most specific — e.g. an
    ///     orchestration repo's <c>CLAUDE.md</c> followed by a git-submodule's own).
    ///     <para>
    ///     <paramref name="workspaceRoot" /> itself is always checked regardless of whether it's a
    ///     git repo, but the walk only continues to a parent directory when the <em>current</em>
    ///     level has a <c>.git</c> entry (directory for a normal repo, file for a submodule/worktree)
    ///     — otherwise it stops there. Climbing unconditionally to the real filesystem root would
    ///     pick up an unrelated <c>CLAUDE.md</c> from any ancestor directory that happens to have
    ///     one (e.g. the user's home directory) with nothing to do with this project; bounding the
    ///     walk to actual repo nesting is what makes the discovered chain meaningful.
    ///     </para>
    /// </summary>
    private static List<(string Path, string Content)> DiscoverClaudeMdChain(string workspaceRoot)
    {
        List<(string Path, string Content)> chain = [];

        string globalPath = InstructionOptimizerService.GlobalClaudeInstructionsPath;
        if (File.Exists(globalPath))
        {
            chain.Add((globalPath, File.ReadAllText(globalPath)));
        }

        List<string> projectPaths = [];
        DirectoryInfo? dir = new(workspaceRoot);
        while (dir is not null)
        {
            string? candidate = ResolveClaudeMdCandidate(dir.FullName);
            if (candidate is not null && !string.Equals(candidate, globalPath, StringComparison.OrdinalIgnoreCase))
            {
                projectPaths.Add(candidate);
            }

            string gitMarker = Path.Combine(dir.FullName, ".git");
            if (!Directory.Exists(gitMarker) && !File.Exists(gitMarker))
            {
                break;
            }

            dir = dir.Parent;
        }

        projectPaths.Reverse();
        foreach (string path in projectPaths)
        {
            chain.Add((path, File.ReadAllText(path)));
        }

        return chain;
    }

    /// <summary>
    ///     Resolves the CLAUDE.md-equivalent file for one directory level in the chain walk,
    ///     preferring <c>CLAUDE.human.md</c> over <c>CLAUDE.md</c> when both exist. In practice
    ///     only the workspace root ever has a <c>CLAUDE.human.md</c> — the rename that creates it
    ///     (<c>InstructionOptimizerService.EnsureHumanSourcePreserved</c>, gated behind
    ///     <c>repoHelper.combineClaudeMdForClaudeCode</c>) is scoped to the workspace root only, so
    ///     ancestor repos and the global instructions file are never renamed. Checking every level
    ///     uniformly costs nothing and avoids a special case for "only the last level."
    /// </summary>
    private static string? ResolveClaudeMdCandidate(string directory)
    {
        string humanPath = Path.Combine(directory, "CLAUDE.human.md");
        if (File.Exists(humanPath))
        {
            return humanPath;
        }

        string claudeMdPath = Path.Combine(directory, "CLAUDE.md");
        return File.Exists(claudeMdPath) ? claudeMdPath : null;
    }

    /// <summary>
    ///     Resolves the same chain as <see cref="EnsureFresh" /> (global instructions, then every
    ///     ancestor repo's CLAUDE.md, then the workspace root's own, outermost first) but returns
    ///     only the source paths — used by <c>ClaudeMdExcludesWriter</c> to know which files'
    ///     content has been folded into the workspace's regenerated <c>CLAUDE.md</c>, so Claude
    ///     Code's own <c>claudeMdExcludes</c> setting can skip loading them a second time natively.
    /// </summary>
    public static IReadOnlyList<string> GetChainSourcePaths(string workspaceRoot)
    {
        return [.. DiscoverClaudeMdChain(workspaceRoot).Select(entry => entry.Path)];
    }

    /// <summary>
    ///     Called only when <see cref="DiscoverClaudeMdChain" /> found nothing at all — no global
    ///     doc, no project-level one anywhere up the chain. Since <c>repoHelper.optimizeInstructions</c>
    ///     is on by default (see <see cref="InstructionOptimizerService" />), a workspace with no
    ///     <c>CLAUDE.md</c> yet would otherwise silently never get any instruction sync at all,
    ///     with no user-visible signal that the feature exists — so a minimal starter doc is
    ///     created at the workspace root, once, without asking, the same way
    ///     <c>WorkspaceConfigDefaults.EnsureDefaults</c> silently bootstraps <c>config.json</c> and
    ///     the ignore files. Best-effort: an I/O failure here must never block session connect.
    /// </summary>
    private IReadOnlyList<(string Path, string Content)> BootstrapWorkspaceClaudeMd(string workspaceRoot)
    {
        string path = Path.Combine(workspaceRoot, "CLAUDE.md");
        try
        {
            File.WriteAllText(path, StarterClaudeMdContent);
            LogBootstrapped(_logger, workspaceRoot, path);
            return [(path, StarterClaudeMdContent)];
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            LogBootstrapFailed(_logger, workspaceRoot, ex);
            return [];
        }
    }

    /// <summary>
    ///     A single-doc chain (the common case — no project <c>CLAUDE.md</c> found) caches
    ///     verbatim with no added framing, preserving the pre-chain-walk behavior. A multi-doc
    ///     chain gets each entry prefixed with a source-path comment so the concatenated result
    ///     reads as a labeled digest rather than an unattributed merge.
    /// </summary>
    private static string BuildCombinedMainContent(IReadOnlyList<(string Path, string Content)> chain)
    {
        if (chain.Count == 1)
        {
            return chain[0].Content;
        }

        StringBuilder sb = new();
        foreach ((string path, string content) in chain)
        {
            if (sb.Length > 0)
            {
                sb.Append("\n\n");
            }

            sb.Append("<!-- source: ").Append(path).Append(" -->\n").Append(content);
        }

        return sb.ToString();
    }

    /// <summary>
    ///     Returns the cached content of the first sub-doc whose <c>taskTypes</c> frontmatter
    ///     includes <paramref name="taskType" />, or <see langword="null" /> if none matches (or the
    ///     cache couldn't be refreshed). Regenerates the cache first if the source has changed.
    /// </summary>
    public string? TryGetInjectableDoc(string workspaceRoot, TaskType taskType)
    {
        InstructionManifest manifest = EnsureFresh(workspaceRoot);
        string taskTypeName = taskType.ToString();

        InstructionManifestSubDoc? match = manifest.SubDocs.FirstOrDefault(
            d => d.TaskTypes.Contains(taskTypeName, StringComparer.OrdinalIgnoreCase));

        if (match is null)
        {
            return null;
        }

        string path = Path.Combine(SubDocsDir(workspaceRoot), match.Slug + ".md");
        return File.Exists(path) ? File.ReadAllText(path) : null;
    }

    private InstructionManifest Regenerate(
        string workspaceRoot, string mainContent, List<DiscoveredSubDoc> subDocs, string sourceHash)
    {
        string cacheDir = CacheDir(workspaceRoot);
        string subDocsDir = SubDocsDir(workspaceRoot);
        Directory.CreateDirectory(subDocsDir);

        // Clear stale sub-doc files from a previous generation before writing the current set —
        // a sub-doc removed from the main doc (or renamed) must not leave an orphaned cache entry
        // that TryGetInjectableDoc's manifest lookup would never point to but that lingers on disk.
        foreach (string stale in Directory.EnumerateFiles(subDocsDir, "*.md"))
        {
            File.Delete(stale);
        }

        File.WriteAllText(Path.Combine(cacheDir, "main.md"), mainContent);

        List<InstructionManifestSubDoc> manifestSubDocs = new(subDocs.Count);
        foreach (DiscoveredSubDoc doc in subDocs)
        {
            File.WriteAllText(Path.Combine(subDocsDir, doc.Slug + ".md"), doc.BodyContent);
            manifestSubDocs.Add(new InstructionManifestSubDoc(
                doc.RelativeSourcePath, doc.Slug, doc.FrontMatter.PathGlobs, doc.FrontMatter.TaskTypes));
        }

        InstructionManifest manifest = new()
        {
            SourceHash = sourceHash,
            GeneratedAtUtc = DateTimeOffset.UtcNow,
            SubDocs = manifestSubDocs,
        };

        File.WriteAllText(Path.Combine(cacheDir, "manifest.json"), JsonSerializer.Serialize(manifest, JsonOptions));
        LogRegenerated(_logger, workspaceRoot, manifestSubDocs.Count);

        return manifest;
    }

    private static InstructionManifest? ReadManifest(string manifestPath)
    {
        if (!File.Exists(manifestPath))
        {
            return null;
        }

        try
        {
            return JsonSerializer.Deserialize<InstructionManifest>(File.ReadAllText(manifestPath));
        }
        catch (Exception ex) when (ex is JsonException or IOException or UnauthorizedAccessException)
        {
            // IOException in particular is a real, expected race here, not just defensive
            // belt-and-suspenders: the FileSystemWatcher-triggered background regeneration (see
            // EnsureWatcherStarted/OnSourceChanged) can be mid-write to this same manifest.json
            // on another thread at the exact moment a caller on this thread reads it. Treating
            // that as "no existing manifest" is safe — it just means this call falls through to
            // Regenerate() and recomputes, same as a first-ever run.
            return null;
        }
    }

    private static string ComputeSourceHash(
        IReadOnlyList<(string Path, string Content)> chain, IReadOnlyList<DiscoveredSubDoc> subDocs)
    {
        StringBuilder sb = new();
        foreach ((string path, string content) in chain)
        {
            sb.Append(path).Append(' ').Append(content).Append(' ');
        }

        foreach (DiscoveredSubDoc doc in subDocs.OrderBy(d => d.RelativeSourcePath, StringComparer.OrdinalIgnoreCase))
        {
            sb.Append(' ').Append(doc.RelativeSourcePath).Append(' ').Append(doc.RawContent);
        }

        byte[] hash = SHA256.HashData(Encoding.UTF8.GetBytes(sb.ToString()));
        return Convert.ToHexStringLower(hash);
    }

    // ── File-system watcher ──────────────────────────────────────────────────────

    private void EnsureWatcherStarted()
    {
        if (_watcher is not null)
        {
            return;
        }

        lock (_watcherSync)
        {
            #pragma warning disable CA1508 // Double-checked locking: _watcher can be set on another thread between the two checks.
            if (_watcher is not null)
            {
                return;
            }
            #pragma warning restore CA1508

            string? globalDir = Path.GetDirectoryName(InstructionOptimizerService.GlobalClaudeInstructionsPath);
            if (string.IsNullOrEmpty(globalDir) || !Directory.Exists(globalDir))
            {
                return;
            }

            FileSystemWatcher watcher = new(globalDir, "*.md")
            {
                IncludeSubdirectories = true,
                NotifyFilter = NotifyFilters.LastWrite | NotifyFilters.FileName | NotifyFilters.CreationTime,
            };
            watcher.Changed += OnSourceChanged;
            watcher.Created += OnSourceChanged;
            watcher.Deleted += OnSourceChanged;
            watcher.Renamed += OnSourceChanged;
            watcher.EnableRaisingEvents = true;
            _watcher = watcher;
        }
    }

    private void OnSourceChanged(object sender, FileSystemEventArgs e)
    {
        string[] roots = [.. _knownWorkspaceRoots.Keys];
        LogSourceChanged(_logger, roots.Length);

        foreach (string root in roots)
        {
            try
            {
                EnsureFresh(root);
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
            {
                LogRegenerationFailed(_logger, root, ex);
            }
        }
    }

    public void Dispose()
    {
        _watcher?.Dispose();
    }
}

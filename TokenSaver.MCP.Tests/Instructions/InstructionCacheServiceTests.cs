using AiDevTools.TokenSaver.ContextHelper.Models;
using AiDevTools.TokenSaver.MCP.Services;

using Microsoft.Extensions.Logging.Abstractions;

using Xunit;

namespace AiDevTools.TokenSaver.MCP.Tests;

[Collection("GlobalConfigDirEnvVar")]
public sealed class InstructionCacheServiceTests : IDisposable
{
    private const string GlobalClaudeMdEnvVar = "TOKENSAVER_GLOBAL_CLAUDE_MD_PATH";

    private readonly string _workspaceRoot;
    private readonly string _claudeDir;
    private readonly string _globalClaudeMdPath;
    private readonly InstructionCacheService _cache;

    public InstructionCacheServiceTests()
    {
        _workspaceRoot = Directory.CreateTempSubdirectory("icsTests-workspace-").FullName;
        _claudeDir = Directory.CreateTempSubdirectory("icsTests-claude-").FullName;
        _globalClaudeMdPath = Path.Combine(_claudeDir, "CLAUDE.md");
        Environment.SetEnvironmentVariable(GlobalClaudeMdEnvVar, _globalClaudeMdPath);

        _cache = new InstructionCacheService(NullLogger<InstructionCacheService>.Instance);
    }

    public void Dispose()
    {
        _cache.Dispose();
        Environment.SetEnvironmentVariable(GlobalClaudeMdEnvVar, null);
        try
        {
            Directory.Delete(_workspaceRoot, recursive: true);
        }
        catch (IOException)
        {
        }

        try
        {
            Directory.Delete(_claudeDir, recursive: true);
        }
        catch (IOException)
        {
        }
    }

    private string CacheDir => Path.Combine(_workspaceRoot, ".tokensaver", "context", "instructions");

    [Fact]
    public void EnsureFresh_NoDocsAnywhere_BootstrapsStarterClaudeMdAtWorkspaceRoot()
    {
        InstructionManifest manifest = _cache.EnsureFresh(_workspaceRoot);

        Assert.Empty(manifest.SubDocs);
        Assert.NotEmpty(manifest.SourceHash);
        string bootstrappedPath = Path.Combine(_workspaceRoot, "CLAUDE.md");
        Assert.True(File.Exists(bootstrappedPath), "A starter CLAUDE.md must be created when none exists anywhere.");
        Assert.Contains("auto-generated by TokenSaver", File.ReadAllText(bootstrappedPath), StringComparison.Ordinal);
        Assert.True(Directory.Exists(CacheDir));
    }

    [Fact]
    public void EnsureFresh_MainDocOnly_WritesMainAndManifestWithNoSubDocs()
    {
        File.WriteAllText(_globalClaudeMdPath, "# Global rules\nAlways do X.");

        InstructionManifest manifest = _cache.EnsureFresh(_workspaceRoot);

        Assert.Empty(manifest.SubDocs);
        Assert.NotEmpty(manifest.SourceHash);
        Assert.Equal("# Global rules\nAlways do X.", File.ReadAllText(InstructionCacheService.MainDocCachePath(_workspaceRoot)));
    }

    [Fact]
    public void EnsureFresh_MainDocReferencesSubDoc_DiscoversAndCachesIt()
    {
        Directory.CreateDirectory(Path.Combine(_claudeDir, "rules"));
        string subDocPath = Path.Combine(_claudeDir, "rules", "debugging.md");
        File.WriteAllText(
            subDocPath,
            "---\npaths:\n  - \"**/*.cs\"\ntaskTypes:\n  - Debug\n---\n\n# Debugging\nCheck the logs first.");

        File.WriteAllText(
            _globalClaudeMdPath,
            "# Global rules\nDetailed guidance lives in `~/.claude/rules/debugging.md`, loaded on demand.");

        InstructionManifest manifest = _cache.EnsureFresh(_workspaceRoot);

        InstructionManifestSubDoc sub = Assert.Single(manifest.SubDocs);
        Assert.Equal("debugging", sub.Slug);
        Assert.Contains("**/*.cs", sub.PathGlobs);
        Assert.Contains("Debug", sub.TaskTypes);

        string cachedBody = File.ReadAllText(Path.Combine(CacheDir, "subdocs", "debugging.md"));
        Assert.Contains("Check the logs first.", cachedBody, StringComparison.Ordinal);
        Assert.DoesNotContain("taskTypes:", cachedBody, StringComparison.Ordinal);
    }

    [Fact]
    public void EnsureFresh_UnchangedSource_DoesNotRewriteManifest()
    {
        File.WriteAllText(_globalClaudeMdPath, "# Global rules\nAlways do X.");
        _cache.EnsureFresh(_workspaceRoot);
        string manifestPath = Path.Combine(CacheDir, "manifest.json");
        DateTime firstWrite = File.GetLastWriteTimeUtc(manifestPath);

        Thread.Sleep(50);
        InstructionManifest second = _cache.EnsureFresh(_workspaceRoot);

        Assert.Equal(firstWrite, File.GetLastWriteTimeUtc(manifestPath));
        Assert.Empty(second.SubDocs);
    }

    [Fact]
    public void EnsureFresh_SourceChanged_Regenerates()
    {
        File.WriteAllText(_globalClaudeMdPath, "# Global rules\nAlways do X.");
        InstructionManifest first = _cache.EnsureFresh(_workspaceRoot);

        File.WriteAllText(_globalClaudeMdPath, "# Global rules\nAlways do Y instead.");
        InstructionManifest second = _cache.EnsureFresh(_workspaceRoot);

        Assert.NotEqual(first.SourceHash, second.SourceHash);
        Assert.Equal("# Global rules\nAlways do Y instead.", File.ReadAllText(InstructionCacheService.MainDocCachePath(_workspaceRoot)));
    }

    [Fact]
    public void TryGetInjectableDoc_MatchingTaskType_ReturnsSubDocContent()
    {
        Directory.CreateDirectory(Path.Combine(_claudeDir, "rules"));
        File.WriteAllText(
            Path.Combine(_claudeDir, "rules", "debugging.md"),
            "---\ntaskTypes:\n  - Debug\n---\n\nCheck the logs first.");
        File.WriteAllText(
            _globalClaudeMdPath,
            "# Global rules\nSee `~/.claude/rules/debugging.md` when debugging.");

        string? injected = _cache.TryGetInjectableDoc(_workspaceRoot, TaskType.Debug);

        Assert.NotNull(injected);
        Assert.Contains("Check the logs first.", injected, StringComparison.Ordinal);
    }

    [Fact]
    public void TryGetInjectableDoc_NoMatchingTaskType_ReturnsNull()
    {
        Directory.CreateDirectory(Path.Combine(_claudeDir, "rules"));
        File.WriteAllText(
            Path.Combine(_claudeDir, "rules", "debugging.md"),
            "---\ntaskTypes:\n  - Debug\n---\n\nCheck the logs first.");
        File.WriteAllText(
            _globalClaudeMdPath,
            "# Global rules\nSee `~/.claude/rules/debugging.md` when debugging.");

        string? injected = _cache.TryGetInjectableDoc(_workspaceRoot, TaskType.Planning);

        Assert.Null(injected);
    }

    [Fact]
    public void EnsureFresh_ProjectClaudeMdOnly_NoGlobalDoc_CachesItVerbatim()
    {
        File.WriteAllText(Path.Combine(_workspaceRoot, "CLAUDE.md"), "# Project rules\nDo Y.");

        InstructionManifest manifest = _cache.EnsureFresh(_workspaceRoot);

        Assert.NotEmpty(manifest.SourceHash);
        Assert.Equal("# Project rules\nDo Y.", File.ReadAllText(InstructionCacheService.MainDocCachePath(_workspaceRoot)));
    }

    [Fact]
    public void EnsureFresh_GlobalAndWorkspaceClaudeMd_ConcatenatesGlobalBeforeProject()
    {
        File.WriteAllText(_globalClaudeMdPath, "GLOBAL_MARKER");
        File.WriteAllText(Path.Combine(_workspaceRoot, "CLAUDE.md"), "WORKSPACE_MARKER");

        _cache.EnsureFresh(_workspaceRoot);
        string cached = File.ReadAllText(InstructionCacheService.MainDocCachePath(_workspaceRoot));

        Assert.Contains("GLOBAL_MARKER", cached, StringComparison.Ordinal);
        Assert.Contains("WORKSPACE_MARKER", cached, StringComparison.Ordinal);
        Assert.True(
            cached.IndexOf("GLOBAL_MARKER", StringComparison.Ordinal) < cached.IndexOf("WORKSPACE_MARKER", StringComparison.Ordinal),
            "Global doc must precede the workspace's own doc, mirroring Claude Code's own ordering.");
    }

    [Fact]
    public void EnsureFresh_NonGitAncestorHasClaudeMd_DoesNotLeakIntoChain()
    {
        // _workspaceRoot is a plain temp directory with no .git marker — the walk must stop
        // right there and never climb to check its parent (the shared system temp directory)
        // for an unrelated CLAUDE.md, even though one exists there.
        string parentDir = Directory.GetParent(_workspaceRoot)!.FullName;
        string unrelatedAncestorDoc = Path.Combine(parentDir, "CLAUDE.md");
        bool createdUnrelatedDoc = !File.Exists(unrelatedAncestorDoc);
        if (createdUnrelatedDoc)
        {
            File.WriteAllText(unrelatedAncestorDoc, "UNRELATED_ANCESTOR_MARKER");
        }

        try
        {
            File.WriteAllText(Path.Combine(_workspaceRoot, "CLAUDE.md"), "WORKSPACE_MARKER");

            _cache.EnsureFresh(_workspaceRoot);
            string cached = File.ReadAllText(InstructionCacheService.MainDocCachePath(_workspaceRoot));

            Assert.DoesNotContain("UNRELATED_ANCESTOR_MARKER", cached, StringComparison.Ordinal);
            Assert.Equal("WORKSPACE_MARKER", cached);
        }
        finally
        {
            if (createdUnrelatedDoc)
            {
                File.Delete(unrelatedAncestorDoc);
            }
        }
    }

    [Fact]
    public void EnsureFresh_AncestorAndWorkspaceClaudeMd_WalksUpAndOrdersOutermostFirst()
    {
        string ancestorRoot = Directory.CreateTempSubdirectory("icsTests-ancestor-").FullName;
        string nestedWorkspace = Path.Combine(ancestorRoot, "child");
        Directory.CreateDirectory(nestedWorkspace);
        try
        {
            // A .git marker at the nested workspace is what allows the walk to continue up to
            // the ancestor at all — without one, DiscoverClaudeMdChain stops right at
            // nestedWorkspace (see its doc comment: climbing past a non-repo directory would
            // risk picking up unrelated ancestor CLAUDE.md files with nothing to do with this
            // project, e.g. the real user's home directory in production).
            Directory.CreateDirectory(Path.Combine(nestedWorkspace, ".git"));
            File.WriteAllText(Path.Combine(ancestorRoot, "CLAUDE.md"), "ANCESTOR_MARKER");
            File.WriteAllText(Path.Combine(nestedWorkspace, "CLAUDE.md"), "CHILD_MARKER");

            _cache.EnsureFresh(nestedWorkspace);
            string cached = File.ReadAllText(InstructionCacheService.MainDocCachePath(nestedWorkspace));

            Assert.Contains("ANCESTOR_MARKER", cached, StringComparison.Ordinal);
            Assert.Contains("CHILD_MARKER", cached, StringComparison.Ordinal);
            Assert.True(
                cached.IndexOf("ANCESTOR_MARKER", StringComparison.Ordinal) < cached.IndexOf("CHILD_MARKER", StringComparison.Ordinal),
                "The broader ancestor doc must precede the more specific workspace doc.");
        }
        finally
        {
            try
            {
                Directory.Delete(ancestorRoot, recursive: true);
            }
            catch (IOException)
            {
            }
        }
    }

    [Fact]
    public void EnsureFresh_WorkspaceClaudeMdReferencesRelativeSubDoc_DiscoversItRelativeToWorkspace()
    {
        Directory.CreateDirectory(Path.Combine(_workspaceRoot, ".claude", "rules"));
        File.WriteAllText(
            Path.Combine(_workspaceRoot, ".claude", "rules", "commands.md"),
            "---\npaths:\n  - \"**/*.slnx\"\n---\n\nRun the build.");
        File.WriteAllText(
            Path.Combine(_workspaceRoot, "CLAUDE.md"),
            "# Project rules\nSee `.claude/rules/commands.md` for build commands.");

        InstructionManifest manifest = _cache.EnsureFresh(_workspaceRoot);

        InstructionManifestSubDoc sub = Assert.Single(manifest.SubDocs);
        Assert.Equal("commands", sub.Slug);
        Assert.Contains("**/*.slnx", sub.PathGlobs);
    }

    [Fact]
    public void EnsureFresh_AutoSplitOversizedFalse_LeavesOversizedDocUnsplitInCache()
    {
        string bigSection = "## Big Section\n" + string.Concat(Enumerable.Repeat("Detail. ", 600));
        File.WriteAllText(_globalClaudeMdPath, "# Global\n\nIntro.\n\n" + bigSection);
        string originalGlobalContent = File.ReadAllText(_globalClaudeMdPath);

        InstructionManifest manifest = _cache.EnsureFresh(_workspaceRoot, autoSplitOversized: false);

        Assert.Empty(manifest.SubDocs);
        Assert.Equal(originalGlobalContent, File.ReadAllText(_globalClaudeMdPath));
        Assert.Equal(originalGlobalContent, File.ReadAllText(InstructionCacheService.MainDocCachePath(_workspaceRoot)));
    }

    [Fact]
    public void EnsureFresh_AutoSplitOversizedTrue_ShrinksCachedMainAndCachesSectionAsSubDoc_WithoutTouchingSourceFile()
    {
        string bigSection = "## Big Section\n" + string.Concat(Enumerable.Repeat("Detail. ", 600));
        string originalGlobalContent = "# Global\n\nIntro.\n\n" + bigSection;
        File.WriteAllText(_globalClaudeMdPath, originalGlobalContent);

        InstructionManifest manifest = _cache.EnsureFresh(_workspaceRoot, autoSplitOversized: true);

        // The real source file is never touched — only the cached representation is split.
        Assert.Equal(originalGlobalContent, File.ReadAllText(_globalClaudeMdPath));

        // The cached main.md is the shrunk version...
        string cachedMain = File.ReadAllText(InstructionCacheService.MainDocCachePath(_workspaceRoot));
        Assert.Contains("loaded on demand", cachedMain, StringComparison.Ordinal);
        Assert.DoesNotContain("Detail. ", cachedMain, StringComparison.Ordinal);

        // ...and the extracted section is discoverable as an ordinary sub-doc, cached under
        // subdocs/ like any backtick-referenced one.
        InstructionManifestSubDoc sub = Assert.Single(manifest.SubDocs);
        Assert.Equal("big-section", sub.Slug);
        string cachedSubDoc = File.ReadAllText(Path.Combine(CacheDir, "subdocs", "big-section.md"));
        Assert.Contains("Detail. ", cachedSubDoc, StringComparison.Ordinal);
    }

    [Fact]
    public void GetChainSourcePaths_GlobalAndWorkspaceDocsExist_ReturnsBothOutermostFirst()
    {
        File.WriteAllText(_globalClaudeMdPath, "# Global rules\nAlways do X.");
        string workspaceClaudeMdPath = Path.Combine(_workspaceRoot, "CLAUDE.md");
        File.WriteAllText(workspaceClaudeMdPath, "# Project rules");

        IReadOnlyList<string> paths = InstructionCacheService.GetChainSourcePaths(_workspaceRoot);

        Assert.Equal([_globalClaudeMdPath, workspaceClaudeMdPath], paths);
    }

    [Fact]
    public void GetChainSourcePaths_HumanMdExistsAtWorkspaceRoot_PrefersItOverClaudeMd()
    {
        string workspaceClaudeMdPath = Path.Combine(_workspaceRoot, "CLAUDE.md");
        string humanPath = Path.Combine(_workspaceRoot, "CLAUDE.human.md");
        File.WriteAllText(workspaceClaudeMdPath, "# Generated pointer");
        File.WriteAllText(humanPath, "# Hand-authored source");

        IReadOnlyList<string> paths = InstructionCacheService.GetChainSourcePaths(_workspaceRoot);

        Assert.Equal([humanPath], paths);
    }

    [Fact]
    public void EnsureFresh_HumanMdExistsAtWorkspaceRoot_ReadsItsContentInsteadOfClaudeMd()
    {
        string workspaceClaudeMdPath = Path.Combine(_workspaceRoot, "CLAUDE.md");
        string humanPath = Path.Combine(_workspaceRoot, "CLAUDE.human.md");
        File.WriteAllText(workspaceClaudeMdPath, "# Generated pointer, ignore me");
        File.WriteAllText(humanPath, "# Hand-authored source content");

        _cache.EnsureFresh(_workspaceRoot);

        string cachedMain = File.ReadAllText(InstructionCacheService.MainDocCachePath(_workspaceRoot));
        Assert.Contains("Hand-authored source content", cachedMain, StringComparison.Ordinal);
        Assert.DoesNotContain("Generated pointer, ignore me", cachedMain, StringComparison.Ordinal);
    }
}
